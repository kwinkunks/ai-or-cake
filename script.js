const ROUNDS = 6;

let deck = [];      // the 6 chosen images: { src, type }
let round = 0;      // 0-based index into deck
let score = 0;
let answered = false;

// Fisher–Yates shuffle (returns a new array)
const shuffle = (arr) => {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

const encode = (src) => src.split('/').map(encodeURIComponent).join('/');

// Build the hover attribution text from the filename.
//   Real photos are Flickr images named YYYY-MM-DD_HH-MM-SS_<Flickr_User>_<id>.ext
//   (underscores in the username become spaces). Their CC terms require credit.
//   Synthetic images get a symmetric "AI-generated" credit so the info icon is
//   present on every image and isn't itself a tell.
const attributionFor = (item) => {
  const base = item.src.split('/').pop().replace(/\.[^.]+$/, '');

  if (item.type === 'real') {
    const parts = base.split('_');
    const year = (parts[0] || '').slice(0, 4);
    const user = parts.slice(2, -1).join(' ').replace(/\s+/g, ' ').trim();
    if (user && year) return `Photo by ${user} (${year}) · via Flickr · CC`;
    if (user) return `Photo by ${user} · via Flickr · CC`;
    return 'Photo via Flickr · CC';
  }

  let tool = 'an AI image generator';
  if (/^Designer/i.test(base)) tool = 'Microsoft Designer';
  else if (/^Gemini/i.test(base)) tool = 'Google Gemini';
  else if (/^M365Copilot/i.test(base)) tool = 'Microsoft 365 Copilot';
  else if (/^dall-e-3/i.test(base)) tool = 'OpenAI DALL·E 3';
  else if (/^dall-e-2/i.test(base)) tool = 'OpenAI DALL·E 2';
  return `AI-generated with ${tool}`;
};

const preload = (src) => { if (src) new Image().src = encode(src); };

const startGame = () => {
  const pool = [
    ...REAL.map((src) => ({ src, type: 'real' })),
    ...SYNTHETIC.map((src) => ({ src, type: 'synthetic' })),
  ];
  deck = shuffle(pool).slice(0, ROUNDS);
  round = 0;
  score = 0;

  document.getElementById('end').classList.add('hidden');
  document.getElementById('game').classList.remove('hidden');
  showImage();
};

const showImage = () => {
  answered = false;
  const current = deck[round];

  document.getElementById('progress').textContent =
    `Image ${round + 1} of ${ROUNDS}`;

  const img = document.getElementById('game-img');
  img.src = encode(current.src);

  document.getElementById('attribution-text').textContent = attributionFor(current);

  const frame = document.getElementById('image-frame');
  frame.classList.remove('correct', 'wrong');

  document.getElementById('reveal').classList.add('hidden');
  setButtonsEnabled(true);

  preload(deck[round + 1] && deck[round + 1].src);
};

const setButtonsEnabled = (on) => {
  document.getElementById('btn-ai').disabled = !on;
  document.getElementById('btn-real').disabled = !on;
};

const guess = (choice) => {
  if (answered) return;
  answered = true;
  setButtonsEnabled(false);

  const current = deck[round];
  const correct = choice === current.type;
  if (correct) score++;

  const frame = document.getElementById('image-frame');
  frame.classList.add(correct ? 'correct' : 'wrong');

  const verdict = document.getElementById('verdict');
  verdict.textContent = correct ? '✓ Correct!' : '✗ Wrong';
  verdict.className = correct ? 'correct' : 'wrong';

  document.getElementById('label').textContent =
    current.type === 'synthetic'
      ? 'This one was AI-generated.'
      : 'This one was a real cake.';

  document.getElementById('reveal').classList.remove('hidden');
};

const next = () => {
  round++;
  if (round < ROUNDS) {
    showImage();
  } else {
    endGame();
  }
};

const endGame = () => {
  document.getElementById('game').classList.add('hidden');

  document.getElementById('final-score').textContent = `${score} / ${ROUNDS}`;

  let msg;
  if (score === ROUNDS) msg = 'Perfect — a real connoisseur!';
  else if (score >= 4) msg = 'Not bad. But AI is getting hard to spot…';
  else if (score >= 2) msg = 'Trickier than it looks, isn’t it?';
  else msg = 'AI fooled you almost every time.';
  document.getElementById('final-msg').textContent = msg;

  document.getElementById('end').classList.remove('hidden');
};

document.addEventListener('DOMContentLoaded', startGame);
